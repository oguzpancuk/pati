// Same rules as mobile's MapScreen: Turkey bounding box, one map for food
// and water whose records are screen-constant markers in a depleting green
// ring (@mobile/map/careMarkers), animals visible at street scale. The
// basemap is the shared pati style (generated by shared/mapstyle/build.mjs,
// imported from mobile via the @mobile alias) — all three clients render
// the same map. Zoom levels are shared numbers with MapScreen; change one,
// change the other.
const TURKEY_BOUNDS = { minLat: 35.8, maxLat: 42.1, minLng: 25.6, maxLng: 44.8 };
const ACTION_CIRCLE_RADIUS_METERS = 100;
// Animals are drawn only near the user (500 m, owner decision 2026-09-08 —
// was 200 m) and from neighbourhood scale on (15 — was 17; overlapping
// avatars fan out now, see @mobile/map/stacks). Same numbers as mobile.
// Keep the zoom an integer: the layer's `step` on zoom evaluates at the
// tile's integer zoom, the avatar gate at the fractional camera zoom.
const ANIMAL_RADIUS_METERS = 500;
const ANIMAL_VISIBLE_MIN_ZOOM = 15;
// The scale the map focuses to after leaving food/water: the 100 m circle
// and the animals inside it should be visible.
const CELEBRATE_ZOOM = 18;
const USER_ZOOM = 16;

// The map's own vocabulary — mirrors mobile's theme/colors.ts mapColors.
const USER_RADIUS_STROKE = 'rgba(33, 32, 30, 0.35)';

// The "AI is checking the photo" interstitial is real since ADR-0005: the
// photo goes up during it and the model says whether it shows the food or
// water the user claims. An approved (or unchecked — the model may be off)
// photo comes back as a token; after "uygun görünüyor" the user explicitly
// confirms, and only that confirm creates the record (owner decision). A
// rejected photo shows the model's reason and offers a retake (mobile
// parity).

const CARE_TYPE_LABEL: Record<CareType, string> = { food: 'mama', water: 'su' };

// Stacked markers (owner, 2026-09-08, P7 item 9) — same rule as mobile's
// MapScreen: from the avatar zoom on, records and avatars that would
// overlap on screen fan out around their spot automatically (no spokes),
// and the user's dot stays put underneath (@mobile/map/stacks). Below it
// the symbol layer's collision placement thins a pile to its freshest.

const EMPTY_FC: GeoJSON.FeatureCollection = { type: 'FeatureCollection', features: [] };

/**
 * Rasterises every marker variant (mobile ships them as PNGs) into the
 * style's image set at the device pixel ratio. setStyle wipes images, so
 * this runs on every style.load; `hasImage` keeps a re-run cheap. Symbol
 * tiles re-layout on their own once an awaited image lands, so the layer
 * may be added before the images are in.
 */
function registerCareMarkerImages(map: maplibregl.Map) {
  const ratio = Math.min(window.devicePixelRatio || 1, 3);
  const px = Math.round(CARE_MARKER_SIZE * ratio);
  for (const { key, type, tone, step, theme } of careMarkerVariants()) {
    if (map.hasImage(key)) continue;
    const img = new Image(px, px);
    img.onload = () => {
      // The decode can outlive the page: map.remove() drops the style and
      // hasImage() would throw on it (review finding).
      if (!map.style || map.hasImage(key)) return;
      const canvas = document.createElement('canvas');
      canvas.width = px;
      canvas.height = px;
      const ctx = canvas.getContext('2d');
      if (!ctx) return;
      ctx.drawImage(img, 0, 0, px, px);
      map.addImage(key, ctx.getImageData(0, 0, px, px), { pixelRatio: ratio });
    };
    img.src = `data:image/svg+xml;charset=utf-8,${encodeURIComponent(
      careMarkerSvg(type, step, theme, tone)
    )}`;
  }
}

export default function MapPage() {
  const navigate = useNavigate();
  const mapEl = useRef<HTMLDivElement>(null);
  const mapRef = useRef<maplibregl.Map | null>(null);
  // Latest GeoJSON per source: setStyle (theme change) wipes sources and
  // layers, so `ensureLayers` re-adds them from these refs on style.load.
  const careMarkersRef = useRef<GeoJSON.FeatureCollection>(EMPTY_FC);
  const userRingRef = useRef<GeoJSON.FeatureCollection>(EMPTY_FC);
  // The last fetched records, the spot the dot is drawn at and the dot
  // marker itself: the map is imperative, so the stack layout is
  // re-applied from these refs by paintMarkers() whenever records,
  // animals, the dot or the zoom change.
  const actionsRef = useRef<CareAction[]>([]);
  const myLocationRef = useRef<Coordinates | null>(null);
  const userDotRef = useRef<maplibregl.Marker | null>(null);
  const animalMarkersRef = useRef<maplibregl.Marker[]>([]);
  // Request generations for the racy loaders (see loadMarkers).
  const markersSeqRef = useRef(0);
  const animalsSeqRef = useRef(0);
  const statusSeqRef = useRef(0);
  // The last fetched animal list: consulted for which ones are in range for
  // the heart animation (instead of reading back from the markers).
  const animalsDataRef = useRef<Animal[]>([]);
  const zoomedInRef = useRef(false);
  const fileRef = useRef<HTMLInputElement>(null);
  const { celebrate } = useBadgeAwards();
  const [hearts, setHearts] = useState<{ id: number; x: number; y: number }[]>([]);

  // Which record the open confirm sheet creates; set by the tile pressed.
  const [dropType, setDropType] = useState<CareType>('food');
  // Per-type status around the user (or the fallback center).
  const [statuses, setStatuses] = useState<Record<CareType, CareStatus> | null>(null);
  const [confirmOpen, setConfirmOpen] = useState(false);
  const [chooserOpen, setChooserOpen] = useState(false);
  // Placeholder "AI is checking the photo" interstitial — same pattern and
  // constants as mobile MapScreen (always approves; the upload runs behind
  // it; a real model later gains the reject path here).
  const [aiCheck, setAiCheck] = useState<'idle' | 'checking' | 'approved' | 'rejected'>('idle');
  // The check's answer: the token the confirm redeems, or the reason a
  // photo was turned down.
  const [photoCheck, setPhotoCheck] = useState<PhotoCheck | null>(null);
  const [rejectReason, setRejectReason] = useState<string | null>(null);
  const [pendingPhoto, setPendingPhoto] = useState<File | null>(null);
  // Invalidates in-flight check timers: dismissing mid-check and reopening
  // must not let the stale timer flip a fresh sheet to a photo-less
  // "approved" (review finding). Bumped on open, cancel, and dismiss.
  const aiCheckRunRef = useRef(0);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [zoomHint, setZoomHint] = useState(false);
  // Minted once per pending photo and revoked on replacement/unmount (the
  // blob-URL-in-render lesson from the add form).
  const pendingPhotoUrl = useMemo(
    () => (pendingPhoto ? URL.createObjectURL(pendingPhoto) : null),
    [pendingPhoto]
  );
  useEffect(
    () => () => {
      if (pendingPhotoUrl) URL.revokeObjectURL(pendingPhotoUrl);
    },
    [pendingPhotoUrl]
  );
  const [myLocation, setMyLocation] = useState<Coordinates | null>(null);
  // Flips once the (rAF-deferred) map exists, so the data effects below
  // re-run instead of bailing out against a still-null mapRef.
  const [mapReady, setMapReady] = useState(false);

  const typeLabel = CARE_TYPE_LABEL[dropType];

  // Animal markers are DOM elements; they follow the zoom gate imperatively
  // (a ref, not an effect) so `syncAnimalMarkers` can also run right after a
  // fetch replaces the marker list.
  const syncAnimalMarkers = useCallback(() => {
    const map = mapRef.current;
    if (!map) return;
    for (const marker of animalMarkersRef.current) {
      if (zoomedInRef.current) marker.addTo(map);
      else marker.remove();
    }
    // Mobile parity: when animals exist but the zoom gate hides them, say so
    // — otherwise a zoomed-out map just looks empty.
    setZoomHint(animalMarkersRef.current.length > 0 && !zoomedInRef.current);
  }, []);

  const positionOf = (action: CareAction): Coordinates => {
    const [lng, lat] = action.location.coordinates;
    return { lat, lng };
  };
  const animalPositionOf = (animal: Animal): Coordinates => {
    const [lng, lat] = animal.location.coordinates;
    return { lat, lng };
  };

  /**
   * Where each record and avatar is drawn at a zoom: from the avatar zoom
   * on, overlapping ones take fan seats around their spot; below it the
   * map is empty (everything sits on its own spot).
   */
  const layoutAt = useCallback((zoom: number) => {
    if (zoom < ANIMAL_VISIBLE_MIN_ZOOM) return [];
    const items = [
      ...actionsRef.current.map((action) => ({ id: `care-${action.id}`, at: positionOf(action) })),
      ...animalsDataRef.current.map((animal) => ({
        id: `animal-${animal.id}`,
        at: animalPositionOf(animal),
      })),
    ];
    const me = myLocationRef.current;
    return layoutStacks(items, zoom, me ? [me] : []);
  }, []);

  /** Where each avatar/record is drawn at a zoom (the hearts read this). */
  const seatsAt = useCallback(
    (zoom: number) => new Map(layoutAt(zoom).map((p) => [p.id, p.drawAt])),
    [layoutAt]
  );

  const paintMarkers = useCallback(() => {
    const map = mapRef.current;
    if (!map) return;
    const actions = actionsRef.current;
    const animals = animalsDataRef.current;
    const draw = new Map<string, { drawAt: Coordinates; spot: Coordinates | null }>();
    for (const placed of layoutAt(map.getZoom())) {
      draw.set(placed.id, { drawAt: placed.drawAt, spot: placed.spot });
    }
    careMarkersRef.current = featureCollection(
      actions.map((action) => {
        const weight = Number(action.weight);
        const at = draw.get(`care-${action.id}`)?.drawAt ?? positionOf(action);
        // `step` as a string: the icon key is built with `concat`, and a
        // string leaves no room for an engine to print a number as "5.0".
        return pointFeature(at, {
          id: action.id,
          type: action.action_type,
          tone: ringTone(weight),
          step: String(ringStep(weight)),
          weight,
        });
      })
    );
    const source = (id: string) => map.getSource(id) as maplibregl.GeoJSONSource | undefined;
    source('care-markers')?.setData(careMarkersRef.current);
    // The avatars are DOM markers in the same order as animalsDataRef.
    animals.forEach((animal, i) => {
      const at = draw.get(`animal-${animal.id}`)?.drawAt ?? animalPositionOf(animal);
      animalMarkersRef.current[i]?.setLngLat([at.lng, at.lat]);
    });
  }, [layoutAt]);

  /**
   * The user's location as a small dot with a breathing halo (owner, P7
   * item 9 — the paw pin of 2026-08-31 retired), centred on the coordinate;
   * one marker, moved on every fix. The stack layout keeps its spot clear
   * and the animal range ring follows it.
   */
  const placeUserDot = useCallback(
    (loc: Coordinates) => {
      const map = mapRef.current;
      if (!map) return;
      if (!userDotRef.current) {
        const dot = document.createElement('div');
        dot.className = 'user-dot';
        dot.innerHTML = '<span class="user-dot-halo"></span><span class="user-dot-core"></span>';
        // setLngLat before addTo: a marker added without a position is
        // painted at the map's origin until its next update.
        userDotRef.current = new maplibregl.Marker({ element: dot, anchor: 'center' })
          .setLngLat([loc.lng, loc.lat])
          .addTo(map);
      } else {
        userDotRef.current.setLngLat([loc.lng, loc.lat]);
      }
      myLocationRef.current = loc;
      userRingRef.current = featureCollection([circleRing(loc, ANIMAL_RADIUS_METERS)]);
      (map.getSource('user-ring') as maplibregl.GeoJSONSource | undefined)?.setData(
        userRingRef.current
      );
      paintMarkers();
    },
    [paintMarkers]
  );

  /** The locate button (owner, P7 item 11): a fresh fix, dot and ring
   * follow, then fly there; animals and statuses refetch through the
   * `myLocation` effects. */
  async function locateMe() {
    const map = mapRef.current;
    if (!map) return;
    try {
      const loc = await getCurrentLocation();
      setMyLocation(loc);
      placeUserDot(loc);
      map.flyTo({ center: [loc.lng, loc.lat], zoom: USER_ZOOM, duration: 500 });
    } catch (err) {
      setError(describeLocationError(err));
    }
  }

  // The map is built once; data layers refresh in separate effects.
  // Creation is deferred by one animation frame so React StrictMode's
  // dev-mode mount→unmount→mount never creates and immediately removes a
  // half-initialized map (a create/remove/create in the same tick left the
  // second map's style permanently unparsed with maplibre-gl 6.6.0): the
  // first mount cancels the frame before any map exists, only the second
  // mount builds one.
  useEffect(() => {
    if (!mapEl.current || mapRef.current) return;
    let cleanupMap: (() => void) | null = null;
    const frame = requestAnimationFrame(() => {
      cleanupMap = createMap();
    });
    return () => {
      cancelAnimationFrame(frame);
      cleanupMap?.();
    };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  function createMap(): (() => void) | null {
    if (!mapEl.current) return null;
    const map = new maplibregl.Map({
      container: mapEl.current,
      style: styleFor(resolvedThemeName()),
      center: [FALLBACK_CENTER.lng, FALLBACK_CENTER.lat],
      zoom: 15,
      maxBounds: [
        [TURKEY_BOUNDS.minLng, TURKEY_BOUNDS.minLat],
        [TURKEY_BOUNDS.maxLng, TURKEY_BOUNDS.maxLat],
      ],
      // Same ceiling as mobile's MAX_ZOOM; the default (22) overzooms into
      // stretched vector tiles.
      maxZoom: 19,
      attributionControl: { compact: true },
    });
    // No zoom control (handoff): pinch and double-tap are enough.

    // Re-added on every style.load: the initial load and each theme switch.
    const ensureLayers = () => {
      if (map.getSource('care-markers')) return;
      registerCareMarkerImages(map);
      map.addSource('care-markers', { type: 'geojson', data: careMarkersRef.current });
      // One symbol layer, same expressions as mobile: the image key from
      // type + ring step + the current theme, icons shrinking toward
      // country zoom, and collision placement where the fresher record
      // (lower sort key) wins.
      map.addLayer({
        id: 'care-markers-icon',
        type: 'symbol',
        source: 'care-markers',
        layout: {
          'icon-image': [
            'concat',
            'care-',
            ['get', 'type'],
            '-',
            ['get', 'tone'],
            '-',
            ['get', 'step'],
            `-${resolvedThemeName()}`,
          ],
          'icon-size': [
            'interpolate',
            ['linear'],
            ['zoom'],
            CARE_MARKER_ZOOM_SMALL,
            CARE_MARKER_SCALE_SMALL,
            CARE_MARKER_ZOOM_FULL,
            1,
          ],
          // From the avatar zoom on the fan has already separated the stacks,
          // so every marker shows; below it collision placement thins a pile
          // to its freshest record (lower sort key wins).
          'icon-allow-overlap': ['step', ['zoom'], false, ANIMAL_VISIBLE_MIN_ZOOM, true],
          'icon-ignore-placement': ['step', ['zoom'], false, ANIMAL_VISIBLE_MIN_ZOOM, true],
          'symbol-sort-key': ['-', 1, ['get', 'weight']],
        },
      });
      // The user's animal range (where animals draw) as a dashed ring — the
      // handoff's depiction.
      map.addSource('user-ring', { type: 'geojson', data: userRingRef.current });
      map.addLayer({
        id: 'user-ring-stroke',
        type: 'line',
        source: 'user-ring',
        minzoom: ANIMAL_VISIBLE_MIN_ZOOM,
        paint: { 'line-color': USER_RADIUS_STROKE, 'line-width': 1.2, 'line-dasharray': [4, 6] },
      });
    };
    map.on('style.load', ensureLayers);

    const onZoom = () => {
      const next = map.getZoom() >= ANIMAL_VISIBLE_MIN_ZOOM;
      if (next !== zoomedInRef.current) {
        zoomedInRef.current = next;
        syncAnimalMarkers();
        // The stack layout only exists above the gate: repaint on crossing.
        paintMarkers();
      }
    };
    map.on('zoom', onZoom);

    // The stack layout is a screen-space rule: re-seat after every zoom.
    map.on('zoomend', paintMarkers);

    // The OS can flip light/dark while the map is open; the app theme is CSS
    // (instant), the basemap needs a setStyle. ensureLayers restores our
    // sources afterwards; DOM markers survive a style swap on their own.
    const scheme = matchMedia('(prefers-color-scheme: dark)');
    const onScheme = () => map.setStyle(styleFor(resolvedThemeName()));
    scheme.addEventListener('change', onScheme);

    mapRef.current = map;
    setMapReady(true);

    getCurrentLocation()
      .then((loc) => {
        // The location can arrive after leaving the page; guard against the
        // map having been removed.
        if (mapRef.current !== map) return;
        setMyLocation(loc);
        map.jumpTo({ center: [loc.lng, loc.lat], zoom: USER_ZOOM });
        placeUserDot(loc);
      })
      .catch(() => {
        /* Without a location we stay on Kadıköy; asked again when adding a record. */
      });

    return () => {
      scheme.removeEventListener('change', onScheme);
      for (const marker of animalMarkersRef.current) marker.remove();
      animalMarkersRef.current = [];
      map.remove();
      mapRef.current = null;
    };
  }

  const loadMarkers = useCallback(async () => {
    const map = mapRef.current;
    if (!map) return;
    // Overlapping loads (a drop right after the first load) race: without
    // this, whichever response lands LAST paints the map.
    const seq = ++markersSeqRef.current;
    const actions = await fetchCareActionsInBounds(TURKEY_BOUNDS);
    if (seq !== markersSeqRef.current) return;
    actionsRef.current = actions;
    paintMarkers();
  }, [paintMarkers]);

  /** Both statuses around a point; a failed pair leaves the sheet cautious. */
  const loadStatuses = useCallback(async (center: Coordinates) => {
    const seq = ++statusSeqRef.current;
    try {
      const [food, water] = await Promise.all([
        fetchCareStatus(center.lat, center.lng, 'food'),
        fetchCareStatus(center.lat, center.lng, 'water'),
      ]);
      if (seq === statusSeqRef.current) setStatuses({ food, water });
    } catch {
      if (seq === statusSeqRef.current) setStatuses(null);
    }
  }, []);

  const loadAnimals = useCallback(
    async (around?: Coordinates) => {
      const map = mapRef.current;
      if (!map) return;
      const center = around ?? myLocation ?? FALLBACK_CENTER;
      const seq = ++animalsSeqRef.current;
      const animals: Animal[] = await fetchAnimals(center.lat, center.lng, ANIMAL_RADIUS_METERS);
      if (seq !== animalsSeqRef.current) return;
      animalsDataRef.current = animals;
      for (const marker of animalMarkersRef.current) marker.remove();
      animalMarkersRef.current = animals.map((animal) => {
        const [lng, lat] = animal.location.coordinates;
        // The animal's pattern avatar is the marker itself — the avatar in a
        // 42px white circle (handoff size).
        const el = document.createElement('div');
        el.className = 'animal-marker';
        // The face cut-out when the animal has one, the pattern avatar
        // otherwise (P3) — the same rule as AnimalAvatar.
        if (animal.cover_thumb_url) {
          const img = document.createElement('img');
          img.src = animal.cover_thumb_url;
          img.alt = '';
          img.width = 30;
          img.height = 30;
          img.style.cssText =
            'width:30px;height:30px;border-radius:50%;object-fit:cover;display:block';
          el.replaceChildren(img);
        } else {
          el.innerHTML = animalAvatarSvg(animal.species, animal.breed, 30);
        }
        el.addEventListener('click', () => navigate(`/hayvanlar/${animal.id}`));
        return new maplibregl.Marker({ element: el }).setLngLat([lng, lat]);
      });
      syncAnimalMarkers();
      // Seat the new markers: the layout moves the markers that exist now,
      // not the ones just removed (review finding).
      paintMarkers();
    },
    [myLocation, navigate, paintMarkers, syncAnimalMarkers]
  );

  useEffect(() => {
    if (!mapReady) return;
    loadMarkers().catch((err) => setError(err.message));
  }, [mapReady, loadMarkers]);

  useEffect(() => {
    if (!mapReady) return;
    loadAnimals().catch(() => {});
  }, [mapReady, loadAnimals]);

  useEffect(() => {
    loadStatuses(myLocation ?? FALLBACK_CENTER);
  }, [myLocation, loadStatuses]);

  /**
   * Hearts rise from the avatars of the animals within range (100 m) of the
   * dropped food/water. The map zooms to that area first (avatars only draw
   * up close); screen points are computed once movement ends (moveend).
   */
  function celebrateNearbyAnimals(origin: Coordinates) {
    const map = mapRef.current;
    if (!map) return;
    const here = new maplibregl.LngLat(origin.lng, origin.lat);
    const affected = animalsDataRef.current.filter((a) => {
      const [lng, lat] = a.location.coordinates;
      return here.distanceTo(new maplibregl.LngLat(lng, lat)) <= ACTION_CIRCLE_RADIUS_METERS;
    });
    const fire = () => {
      if (affected.length === 0) return;
      // Hearts rise from where the avatar is drawn — its fan seat when it
      // shares the spot with the fresh record (review finding).
      const seats = seatsAt(map.getZoom());
      setHearts(
        affected.map((a) => {
          const at = seats.get(`animal-${a.id}`) ?? animalPositionOf(a);
          const pt = map.project([at.lng, at.lat]);
          return { id: a.id, x: pt.x, y: pt.y };
        })
      );
      window.setTimeout(() => setHearts([]), HEART_BURST_MS + 200);
    };
    map.once('moveend', fire);
    map.flyTo({ center: here, zoom: CELEBRATE_ZOOM, duration: 400 });
  }

  /**
   * Photo picked → it goes up and the model looks at it → the approved step
   * waits for an explicit confirm (owner decision — the check must not
   * auto-add); a rejected photo shows the reason and a retake.
   */
  async function handlePhotoPicked(file: File) {
    setError(null);
    setPendingPhoto(file);
    setPhotoCheck(null);
    setRejectReason(null);
    setAiCheck('checking');
    const run = ++aiCheckRunRef.current;
    try {
      const result = await checkCarePhoto(dropType, file);
      if (run !== aiCheckRunRef.current) return;
      setPhotoCheck(result);
      setAiCheck('approved');
    } catch (err) {
      if (run !== aiCheckRunRef.current) return;
      if (err instanceof ApiError && err.code === 'photoRejected') {
        setRejectReason(err.message);
        setAiCheck('rejected');
        return;
      }
      setAiCheck('idle');
      setPendingPhoto(null);
      setError(err instanceof Error ? err.message : 'Fotoğraf yüklenemedi');
    }
  }

  /** The explicit "add it" after the AI check approved the photo. */
  async function handleConfirmDrop() {
    if (!pendingPhoto || !photoCheck) return;
    setBusy(true);
    setError(null);
    // Hoisted: the "already recorded" branch below refreshes around it.
    let loc: Awaited<ReturnType<typeof getCurrentLocation>> | null = null;
    try {
      // Without a location (http origin, no permission), instead of blocking
      // the user we use the map center and state the reason: people drop at
      // the spot they're looking at anyway. The mobile app requires the real
      // location; web is more lenient (see docs/NOTES.md).
      let usedFallback: string | null = null;
      loc = await getCurrentLocation().catch((err) => {
        usedFallback = describeLocationError(err);
        const center = mapRef.current?.getCenter();
        return center ? { lat: center.lat, lng: center.lng } : FALLBACK_CENTER;
      });
      setMyLocation(loc);
      // The dot, its ring and the layout anchor follow the drop's fix.
      placeUserDot(loc);
      const created = await addCareAction(loc.lat, loc.lng, dropType, photoCheck.photoToken);
      if (usedFallback) setError(`${usedFallback} Kayıt haritanın ortasına düştü.`);
      // aiCheck/pendingPhoto reset when the modal next opens, not here:
      // resetting before the close would flash the confirm content behind it.
      setConfirmOpen(false);
      await Promise.all([loadMarkers(), loadAnimals(loc), loadStatuses(loc)]);
      celebrateNearbyAnimals(loc);
      celebrate(created);
    } catch (err) {
      // Stay on the approval step so the user can retry the confirm —
      // unless the token has expired, which only a fresh check can fix.
      if (err instanceof ApiError && err.code === 'photoAlreadyUsed') {
        // The earlier confirm went through and its response was lost: the
        // drop exists, so close and refresh like a success — and say so if
        // the same flaky connection fails the refresh too.
        setConfirmOpen(false);
        const at = loc;
        try {
          await Promise.all([
            loadMarkers(),
            at ? loadAnimals(at) : Promise.resolve(),
            at ? loadStatuses(at) : Promise.resolve(),
          ]);
        } catch (refreshErr) {
          setError(refreshErr instanceof Error ? refreshErr.message : 'Harita yenilenemedi');
        }
        return;
      }
      if (err instanceof ApiError && err.code === 'photoTokenInvalid') {
        aiCheckRunRef.current++;
        setAiCheck('idle');
        setPendingPhoto(null);
        setPhotoCheck(null);
      }
      setError(err instanceof Error ? err.message : 'Eklenemedi');
    } finally {
      setBusy(false);
    }
  }

  /** A tile pressed: surface the denied-permission guidance, open the sheet for that type. */
  async function openDrop(type: CareType) {
    // Mobile parity, browser-shaped: the browser can't open OS settings,
    // so a denied permission surfaces the guidance text inside the modal
    // up front (web still allows dropping at the map center by design —
    // see docs/NOTES.md).
    try {
      const perm = await navigator.permissions?.query({ name: 'geolocation' });
      if (perm?.state === 'denied') {
        setError(
          'Konum izni verilmedi. Tarayıcı ayarlarından bu siteye konum izni verebilirsin; ' +
            'verilmezse kayıt haritanın ortasına düşer.'
        );
      }
    } catch {
      // Permissions API unavailable (older Safari): behave as before.
    }
    // A leftover 'approved' from the previous run would skip the confirm
    // content (state resets on open, not on close — see handleConfirmDrop).
    aiCheckRunRef.current++;
    setAiCheck('idle');
    setPendingPhoto(null);
    setDropType(type);
    setConfirmOpen(true);
  }

  // The status line reads both types at once; unknown counts as missing
  // (the sheet never claims coverage it hasn't seen) — mobile parity.
  const hasFood = !!statuses && !statuses.food.needsAttention;
  const hasWater = !!statuses && !statuses.water.needsAttention;
  const sheetTitle =
    hasFood && hasWater
      ? 'Bu bölgede mama ve su var'
      : hasFood
      ? 'Bu bölgede mama var, su yok'
      : hasWater
      ? 'Bu bölgede su var, mama yok'
      : 'Buralarda mama ve su yok';

  return (
    <div className="page fill">
      <div ref={mapEl} className="map-root" />

      <div className="map-top">
        {error && <div className="banner">{error}</div>}
        {zoomHint && <div className="zoom-hint">Hayvanları görmek için yakınlaştır</div>}
        {/* The add-to-home-screen invite: hidden when opened from the home
            screen or after "later" (install.tsx). */}
        <InstallBanner compact />
      </div>

      {/* The locate button (P7 item 11) above the sheet. */}
      <button
        className="map-locate"
        aria-label="Konumuma git"
        style={{ bottom: 'calc(178px + env(safe-area-inset-bottom))' }}
        onClick={locateMe}
      >
        <svg
          width="22"
          height="22"
          viewBox="0 0 24 24"
          fill="none"
          stroke="currentColor"
          strokeWidth="1.8"
          strokeLinecap="round"
        >
          <circle cx="12" cy="12" r="7.4" />
          <circle cx="12" cy="12" r="2.2" />
          <path d="M12 2.4v2.6M12 19v2.6M2.4 12H5M19 12h2.6" />
        </svg>
      </button>

      {/* Bottom sheet: both types' status and one "Ekle" that opens the
          chooser (owner, P7 item 10) — mobile parity. */}
      <div className="map-bottom">
        <div className="map-sheet">
          <div className="sheet-handle" />
          <h2>{sheetTitle}</h2>
          <p className="muted" style={{ margin: '2px 0 12px' }}>
            Kayıt şu anki konumuna düşer; halka süre bitene kadar erir.
          </p>
          {/* The pati logo on the button (owner, P8 item 1): white on the
              gradient, heart cut out. logoSvg is our own static markup. */}
          <button className="btn full" onClick={() => setChooserOpen(true)}>
            <span
              className="btn-logo"
              dangerouslySetInnerHTML={{ __html: logoSvg(20, 'currentColor', 'transparent') }}
            />
            Ekle
          </button>
        </div>
      </div>

      {chooserOpen && (
        <div className="backdrop" onClick={() => setChooserOpen(false)}>
          <div className="sheet" onClick={(e) => e.stopPropagation()}>
            <h2>Ne ekliyorsun?</h2>
            {(
              [
                { key: 'food', label: 'Mama bıraktım' },
                { key: 'water', label: 'Su bıraktım' },
                { key: 'animal', label: 'Yeni hayvan' },
              ] as const
            ).map((choice) => (
              <button
                key={choice.key}
                className="chooser-row"
                onClick={async () => {
                  setChooserOpen(false);
                  if (choice.key === 'animal') {
                    const refused = await gateAddAnimal(navigate);
                    if (refused) setError(refused);
                  } else {
                    openDrop(choice.key);
                  }
                }}
              >
                <span className="chooser-icon">
                  {choice.key === 'animal' ? (
                    <svg width="22" height="22" viewBox="0 0 24 24" fill="currentColor">
                      <circle cx="6.4" cy="10.6" r="2.1" />
                      <circle cx="9.9" cy="7.2" r="2.2" />
                      <circle cx="14.1" cy="7.2" r="2.2" />
                      <circle cx="17.6" cy="10.6" r="2.1" />
                      <path d="M12 12.2c2.6 0 5 2.1 5 4.5 0 1.8-1.4 2.9-3 2.9-.9 0-1.4-.4-2-.4s-1.1.4-2 .4c-1.6 0-3-1.1-3-2.9 0-2.4 2.4-4.5 5-4.5Z" />
                    </svg>
                  ) : (
                    <svg
                      width="22"
                      height="22"
                      viewBox="0 0 24 24"
                      fill="none"
                      stroke="currentColor"
                      strokeWidth="1.8"
                      strokeLinecap="round"
                      strokeLinejoin="round"
                    >
                      {CARE_GLYPH_PATHS[choice.key].map((d) => (
                        <path key={d} d={d} />
                      ))}
                    </svg>
                  )}
                </span>
                <span className="chooser-label">{choice.label}</span>
                <span className="chooser-chevron">›</span>
              </button>
            ))}
            <button className="btn ghost full" onClick={() => setChooserOpen(false)}>
              Vazgeç
            </button>
          </div>
        </div>
      )}

      {confirmOpen && (
        <div
          className="backdrop"
          onClick={() => {
            if (busy) return;
            aiCheckRunRef.current++;
            setConfirmOpen(false);
          }}
        >
          <div className="sheet" onClick={(e) => e.stopPropagation()}>
            {/* One file input for every step of the sheet. It used to live
                in the idle branch only, so on the rejected step "Yeniden
                çek" clicked a ref to an unmounted input and did nothing
                (production report, 2026-09-08). */}
            <input
              ref={fileRef}
              type="file"
              accept="image/*"
              capture="environment"
              hidden
              onChange={(e) => {
                const file = e.target.files?.[0];
                if (file) handlePhotoPicked(file);
                e.target.value = '';
              }}
            />
            {aiCheck !== 'idle' ? (
              /* The photo-check interstitial (ADR-0005). The photo is up,
                 nothing is recorded; the approved step waits for an
                 explicit confirm, the rejected step offers a retake. */
              <div style={{ textAlign: 'center', padding: '8px 0 4px' }}>
                <div
                  className="matching-stage"
                  style={{ width: 88, height: 88, margin: '0 auto 12px', position: 'relative' }}
                >
                  {aiCheck === 'checking' ? (
                    <span className="matching-ring" />
                  ) : aiCheck === 'rejected' ? (
                    <span style={{ fontSize: 44, color: 'var(--danger)' }}>✕</span>
                  ) : (
                    <span style={{ fontSize: 44, color: 'var(--success)' }}>✓</span>
                  )}
                </div>
                <h2 style={{ marginBottom: 4 }}>
                  {aiCheck === 'checking'
                    ? 'Yapay zeka fotoğrafı inceliyor'
                    : aiCheck === 'rejected'
                    ? 'Bu fotoğraf uygun görünmüyor'
                    : photoCheck?.verdict === 'approved'
                    ? 'Uygun görünüyor'
                    : 'Fotoğraf hazır'}
                </h2>
                <p className="muted">
                  {aiCheck === 'checking'
                    ? `Fotoğraftaki ${typeLabel} kontrol ediliyor…`
                    : aiCheck === 'rejected'
                    ? rejectReason ?? `Fotoğrafta ${typeLabel} görünmüyor. Tekrar çeker misin?`
                    : `${
                        photoCheck?.reason ? `${photoCheck.reason} ` : ''
                      }Kayıt eklensin mi? Şu anki konumuna ${typeLabel} kaydı düşecek.`}
                </p>
                {aiCheck === 'rejected' && (
                  <>
                    {pendingPhotoUrl && (
                      <img
                        src={pendingPhotoUrl}
                        alt=""
                        width={84}
                        height={84}
                        style={{ objectFit: 'cover', borderRadius: 14, margin: '4px auto 12px' }}
                      />
                    )}
                    <button className="btn full" onClick={() => fileRef.current?.click()}>
                      Yeniden çek
                    </button>
                    <button
                      className="btn ghost full"
                      onClick={() => {
                        aiCheckRunRef.current++;
                        setAiCheck('idle');
                        setPendingPhoto(null);
                        setError(null);
                      }}
                    >
                      Vazgeç
                    </button>
                  </>
                )}
                {aiCheck === 'approved' && (
                  <>
                    {error && <div className="error">{error}</div>}
                    {pendingPhotoUrl && (
                      <img
                        src={pendingPhotoUrl}
                        alt=""
                        width={84}
                        height={84}
                        style={{ objectFit: 'cover', borderRadius: 14, margin: '4px auto 12px' }}
                      />
                    )}
                    <button className="btn full" disabled={busy} onClick={handleConfirmDrop}>
                      {busy ? 'Ekleniyor…' : 'Onayla ve ekle'}
                    </button>
                    <button
                      className="btn ghost full"
                      disabled={busy}
                      onClick={() => {
                        aiCheckRunRef.current++;
                        setAiCheck('idle');
                        setPendingPhoto(null);
                        setError(null);
                      }}
                    >
                      Vazgeç
                    </button>
                  </>
                )}
              </div>
            ) : (
              <>
                <h2>Bulunduğun yere {typeLabel} bırak</h2>
                {/* Upload failures must be visible HERE: the page-level
                    banner sits behind the backdrop (review finding). */}
                {error && <div className="error">{error}</div>}
                <p className="muted">
                  {typeLabel === 'mama' ? 'Mamayı' : 'Suyu'} bırak ve fotoğrafını çek, haritada
                  herkes görsün. Kayıt şu anki konumuna düşecek.
                </p>
                <button
                  className="btn full"
                  disabled={busy}
                  onClick={() => fileRef.current?.click()}
                >
                  📷 Fotoğrafını çek
                </button>
                <button
                  className="btn ghost full"
                  disabled={busy}
                  onClick={() => setConfirmOpen(false)}
                >
                  Vazgeç
                </button>
                {/* A food brand under the food sheet, a water brand under the water one. */}
                <AdBanner
                  slot={dropType === 'food' ? 'food_popup' : 'water_popup'}
                  visible={confirmOpen}
                />
              </>
            )}
          </div>
        </div>
      )}

      {hearts.map((h) => (
        <HeartBurst key={`${h.id}-${h.x}-${h.y}`} x={h.x} y={h.y} />
      ))}
    </div>
  );
}

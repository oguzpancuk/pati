/**
 * Renders the care markers (src/map/careMarkers.ts) and the petshop pin
 * (src/map/petshopMarker.ts) to PNGs for the mobile map's SymbolLayers — MapLibre native takes raster images, and the
 * app has no runtime SVG rasteriser. Web draws the same SVG itself.
 *
 * Usage (Node ≥ 22.18 for the .ts import; Chromium ships with web's
 * Playwright, same as generate-icons.mjs):
 *   node scripts/generate-care-markers.mjs
 *
 * Writes src/map/markers/<key>.png, @2x, @3x and the index.ts that
 * `require`s them (Metro needs literal paths, so the index is generated too).
 * Rerun whenever careMarkers.ts or petshopMarker.ts changes; commit the output.
 */
import { createRequire } from 'node:module';
import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { careMarkerSvg, careMarkerVariants, CARE_MARKER_SIZE } from '../src/map/careMarkers.ts';
import {
  PETSHOP_MARKER_HEIGHT,
  PETSHOP_MARKER_WIDTH,
  PETSHOP_THEMES,
  petshopMarkerKey,
  petshopMarkerSvg,
} from '../src/map/petshopMarker.ts';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'src', 'map', 'markers');
// 1x is written without a suffix: Metro resolves the scale variants from
// it, and jest (no scale logic) needs the plain name to exist so the
// generated index can be required in tests.
const SCALES = [1, 2, 3];

// Playwright is a web/ devDependency; mobile has none.
const requireFromWeb = createRequire(join(ROOT, '..', 'web', 'package.json'));
const { chromium } = requireFromWeb('playwright');


const variants = careMarkerVariants().map(({ key, type, tone, step, theme }) => ({
  key,
  svg: careMarkerSvg(type, step, theme, tone),
  width: CARE_MARKER_SIZE,
  height: CARE_MARKER_SIZE,
}));
const petshops = PETSHOP_THEMES.map((theme) => ({
  key: petshopMarkerKey(theme),
  svg: petshopMarkerSvg(theme),
  width: PETSHOP_MARKER_WIDTH,
  height: PETSHOP_MARKER_HEIGHT,
}));
// Launched before the old PNGs go: a browser that fails to start (a
// Playwright revision with no matching Chromium) used to leave the folder
// empty and the app without a single marker.
const browser = await chromium.launch();
mkdirSync(OUT, { recursive: true });
for (const stale of readdirSync(OUT)) {
  if (stale.endsWith('.png')) rmSync(join(OUT, stale));
}
for (const scale of SCALES) {
  const context = await browser.newContext({
    viewport: { width: CARE_MARKER_SIZE, height: CARE_MARKER_SIZE },
    deviceScaleFactor: scale,
  });
  const page = await context.newPage();
  for (const { key, svg, width, height } of [...variants, ...petshops]) {
    await page.setViewportSize({ width, height });
    await page.setContent(`<body style="margin:0;background:transparent">${svg}</body>`);
    const png = await page.screenshot({ omitBackground: true, type: 'png' });
    writeFileSync(join(OUT, scale === 1 ? `${key}.png` : `${key}@${scale}x.png`), png);
  }
  await context.close();
}
await browser.close();

const entry = ({ key }) => `  '${key}': require('./${key}.png'),`;
writeFileSync(
  join(OUT, 'index.ts'),
  [
    '// Generated by scripts/generate-care-markers.mjs — do not edit; rerun the',
    '// script when careMarkers.ts or petshopMarker.ts changes. Keys match',
    '// careMarkerKey() and petshopMarkerKey().',
    "import type { ImageRequireSource } from 'react-native';",
    '',
    '/* eslint-disable @typescript-eslint/no-var-requires */',
    'export const CARE_MARKER_IMAGES: Record<string, ImageRequireSource> = {',
    ...variants.map(entry),
    '};',
    '',
    'export const PETSHOP_MARKER_IMAGES: Record<string, ImageRequireSource> = {',
    ...petshops.map(entry),
    '};',
    '',
  ].join('\n')
);
console.log(`${variants.length + petshops.length} markers × ${SCALES.length} scales → ${OUT}`);

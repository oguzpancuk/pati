/**
 * Renders the care markers (src/map/careMarkers.ts) to PNGs for the
 * mobile map's SymbolLayer — MapLibre native takes raster images, and the
 * app has no runtime SVG rasteriser. Web draws the same SVG itself.
 *
 * Usage (Node ≥ 22.18 for the .ts import; Chromium ships with web's
 * Playwright, same as generate-icons.mjs):
 *   node scripts/generate-care-markers.mjs
 *
 * Writes src/map/markers/<key>@2x.png, <key>@3x.png and the index.ts that
 * `require`s them (Metro needs literal paths, so the index is generated too).
 * Rerun whenever careMarkers.ts changes; commit the output.
 */
import { createRequire } from 'node:module';
import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { careMarkerSvg, careMarkerVariants, CARE_MARKER_SIZE } from '../src/map/careMarkers.ts';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'src', 'map', 'markers');
const SCALES = [2, 3];

// Playwright is a web/ devDependency; mobile has none.
const requireFromWeb = createRequire(join(ROOT, '..', 'web', 'package.json'));
const { chromium } = requireFromWeb('playwright');

mkdirSync(OUT, { recursive: true });
for (const stale of readdirSync(OUT)) {
  if (stale.endsWith('.png')) rmSync(join(OUT, stale));
}

const variants = careMarkerVariants();
const browser = await chromium.launch();
for (const scale of SCALES) {
  const context = await browser.newContext({
    viewport: { width: CARE_MARKER_SIZE, height: CARE_MARKER_SIZE },
    deviceScaleFactor: scale,
  });
  const page = await context.newPage();
  for (const { key, type, step, theme } of variants) {
    await page.setContent(
      `<body style="margin:0;background:transparent">${careMarkerSvg(type, step, theme)}</body>`
    );
    const png = await page.screenshot({ omitBackground: true, type: 'png' });
    writeFileSync(join(OUT, `${key}@${scale}x.png`), png);
  }
  await context.close();
}
await browser.close();

const lines = variants.map(({ key }) => `  '${key}': require('./${key}.png'),`);
writeFileSync(
  join(OUT, 'index.ts'),
  [
    '// Generated by scripts/generate-care-markers.mjs — do not edit; rerun the',
    '// script when careMarkers.ts changes. Keys match careMarkerKey().',
    "import type { ImageRequireSource } from 'react-native';",
    '',
    '/* eslint-disable @typescript-eslint/no-var-requires */',
    'export const CARE_MARKER_IMAGES: Record<string, ImageRequireSource> = {',
    ...lines,
    '};',
    '',
  ].join('\n')
);
console.log(`${variants.length} markers × ${SCALES.length} scales → ${OUT}`);
